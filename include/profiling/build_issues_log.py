    out = Path(args[0]) if args else INCLUDE.parent / "submission" / "data_issues_log.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    log = build(DEFAULT_DATA_DIR, as_of)
    log.to_csv(out, index=False)
    summary = summarise(log)
