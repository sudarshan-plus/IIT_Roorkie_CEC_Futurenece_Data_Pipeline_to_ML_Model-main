"""
include/profiling/build_issues_log.py
-------------------------------------
Part 0 deliverable: the Data Issues Log, one row per (source row, broken rule):

    file, row_key, source_row, column, problem, quality_dimension, proposed_rule, severity, raw_value

It is generated by running the SAME rulebook the pipelines use over the six source files (so the log and the
quarantine can never disagree), then adding the offending raw value and the column it lives in.

    python include/profiling/build_issues_log.py [out.csv] [--as-of "2026-10-06 09:00:00"]
Writes submission/data_issues_log.csv by default. Customer PII is masked in the log (it is committed to git).
"""

