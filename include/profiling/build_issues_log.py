KEY = {"orders": "order_id", "payments": "payment_id", "customers": "customer_id", "products": "product_id", "stores": "store_id"}
PII_MASKERS = {"email": mask_email, "phone": mask_phone, "full_name": mask_name}


def read(data_dir: Path, kind: str) -> pd.DataFrame:
    df = pd.read_csv(data_dir / SOURCE_FILES[kind], dtype=str, keep_default_na=False)
    df["_source_file"] = SOURCE_FILES[kind]
    df["_source_row_num"] = range(1, len(df) + 1)
    df["_file_seq"] = 0
    return df


def raw_value(row: pd.Series, columns: list[str]) -> str:
    parts = []
    for col in columns:
        value = row[col]
        if col in PII_MASKERS:
            value = PII_MASKERS[col](value) or value
        parts.append(f"{col}={value!r}" if len(columns) > 1 else repr(value))
    return "; ".join(parts)


def build(data_dir: Path, as_of: str) -> pd.DataFrame:
    customers = validate.validate_customers(read(data_dir, "customers"), as_of)
    products = validate.validate_products(read(data_dir, "products"), as_of)
    stores = validate.validate_stores(read(data_dir, "stores"), as_of)
    orders = validate.validate_orders(read(data_dir, "orders"), customers.df, products.df, stores.df, as_of)
    payments = validate.validate_payments(read(data_dir, "payments"), orders.df, as_of)

    records = []
    for scored in (orders, payments, customers, products, stores):
        for _, row in scored.df.iterrows():
            names = [n for n in (row["dq_critical"].split("; ") + row["dq_warnings"].split("; ")) if n]
            for name in names:
                check = dq.BY_NAME[name]
                columns = COLUMNS[name]
                records.append({
                    "file": row["_source_file"],
                    "row_key": row[KEY[scored.table]].strip() or "(blank key)",
                    "source_row": int(row["_source_row_num"]) + 1,       # +1: line number in the file (line 1 is the header)
                    "column": ", ".join(columns),
                    "problem": check.description,
                    "quality_dimension": check.dimension,
                    "proposed_rule": check.name,
                    "severity": check.severity,
                    "raw_value": raw_value(row, columns),
                })
    return pd.DataFrame(records)


def summarise(log: pd.DataFrame) -> pd.DataFrame:
    grouped = log.groupby(["file", "proposed_rule", "column", "problem", "quality_dimension", "severity"], sort=False)
    out = grouped.agg(rows=("row_key", "count"), example_keys=("row_key", lambda s: ", ".join(list(dict.fromkeys(s))[:3]))).reset_index()
    return out.sort_values(["file", "severity", "rows"], ascending=[True, True, False])


